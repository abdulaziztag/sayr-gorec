def chunk_user_message(chunk_text: str, week_label: str, period: str) -> str:
    return (
        f"Неделя {week_label} ({period}). Кусок сообщений форума:\n\n{chunk_text}\n\n"
        "Извлеки факты по схеме."
    )


def synthesis_user_message(
    *, week_label: str, period: str, stats: dict[str, Any], merged: dict[str, Any]
) -> str:
    return (
        f"Неделя {week_label} ({period}).\n\n"
        f"Цифры недели (посчитаны программой, не моделью):\n"
        f"{json.dumps(stats, ensure_ascii=False, indent=1)}\n\n"
        f"Объединённые выжимки из кусков:\n"
        f"{json.dumps(merged, ensure_ascii=False, indent=1)}\n\n"
        "Собери отчёт по схеме."
    )
